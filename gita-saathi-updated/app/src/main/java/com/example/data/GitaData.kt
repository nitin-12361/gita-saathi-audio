    fun getShlokaOfTheDay(): Verse {
        // Pick 2.47 or 18.66 or 4.7 based on day of month
        val dayIndex = (System.currentTimeMillis() / (1000 * 60 * 60 * 24)).toInt() % KEY_VERSES.size
        return KEY_VERSES[dayIndex]
    }

    fun searchVerses(query: String): List<Verse> {
        val cleanQuery = query.trim().lowercase()
        if (cleanQuery.isEmpty()) return emptyList()

        // Check if query is verse reference like "2.47"
        if (cleanQuery.contains(".")) {
            val parts = cleanQuery.split(".")
            if (parts.size == 2) {
                val c = parts[0].toIntOrNull()
                val v = parts[1].toIntOrNull()
                if (c != null && v != null) {
                    val match = getVerse(c, v)
                    if (match != null) return listOf(match)
                }
            }
        }

        val results = mutableListOf<Verse>()
        for (v in KEY_VERSES) {
            if (v.shlokaSanskrit.contains(query, ignoreCase = true) ||
                v.translationHindi.contains(query, ignoreCase = true) ||
                v.translationEnglish.contains(query, ignoreCase = true) ||
                v.transliteration.contains(query, ignoreCase = true) ||
                v.verseReference == cleanQuery
            ) {
                results.add(v)
            }
        }
        return results
    }
